"use client";

import { useEffect, useState, useCallback } from "react";
import { useParams, useRouter } from "next/navigation";
import Link from "next/link";
import { loadAnalysisById, deleteAnalysis } from "@/services/analysisStorage";
import type { MockAnalysisResult } from "@/services/mockAnalysisService";
import AnalysisResultsLayout from "@/components/results/AnalysisResultsLayout";
import { formatDate } from "@/lib/utils";
import {
  ArrowLeft,
  Download,
  Trash2,
  PlusCircle,
  History,
  FileText,
  Calendar,
  Briefcase,
  AlertCircle,
} from "lucide-react";
import Button from "@/components/ui/Button";

export default function ResumeAnalysisPage() {
  const params = useParams();
  const router = useRouter();
  const analysisId = params?.analysisId as string;

  const [result, setResult] = useState<MockAnalysisResult | null>(null);
  const [notFound, setNotFound] = useState(false);
  const [deleting, setDeleting] = useState(false);
  const [saved, setSaved] = useState(false);
  const [exportMsg, setExportMsg] = useState<string | null>(null);

  useEffect(() => {
    if (!analysisId) return;
    const data = loadAnalysisById(analysisId);
    if (!data) setNotFound(true);
    else setResult(data);
  }, [analysisId]);

  // ── Save ──────────────────────────────────────────────────────────────────
  const handleSave = useCallback(() => {
    setSaved(true);
    setTimeout(() => setSaved(false), 2500);
  }, []);

  // ── Delete ────────────────────────────────────────────────────────────────
  const handleDelete = useCallback(() => {
    if (!confirm("Delete this analysis? This cannot be undone.")) return;
    setDeleting(true);
    deleteAnalysis(analysisId);
    router.push("/dashboard/my-resumes");
  }, [analysisId, router]);

  // ── Export ────────────────────────────────────────────────────────────────
  const handleExport = useCallback(() => {
    if (!result) return;
    try {
      const lines: string[] = [
        "RESUME ANALYSIS REPORT — DEMO DATA",
        "=".repeat(50),
        "",
        `⚠  This report contains illustrative demo results only.`,
        `   It is NOT based on AI processing of your actual resume.`,
        "",
        `Job Title:    ${result.jobTitle}`,
        `Target Role:  ${result.targetRole}`,
        `Resume File:  ${result.fileName}`,
        `Date:         ${formatDate(result.createdAt)}`,
        `Match Score:  ${result.matchScore}% (demo estimate)`,
        "",
        "─".repeat(50),
        "SKILLS",
        "─".repeat(50),
        "",
        "Matched Skills:",
        ...result.skills
          .filter((s) => s.matchType === "matched")
          .map((s) => `  ✓ ${s.name}`),
        "",
        "Partial Match:",
        ...result.skills
          .filter((s) => s.matchType === "partial")
          .map((s) => `  ~ ${s.name}`),
        "",
        "Missing Skills:",
        ...result.skills
          .filter((s) => s.matchType === "missing")
          .map((s) => `  ✗ ${s.name}`),
        "",
        "─".repeat(50),
        "ATS READINESS (ESTIMATES)",
        "─".repeat(50),
        "",
        ...result.atsChecks.map(
          (c) => `[${c.status.toUpperCase()}] ${c.label}: ${c.detail}`
        ),
        "",
        "─".repeat(50),
        "STRENGTHS",
        "─".repeat(50),
        "",
        ...result.strengths.map((s, i) => `${i + 1}. ${s}`),
        "",
        "─".repeat(50),
        "RECOMMENDATIONS",
        "─".repeat(50),
        "",
        ...result.recommendations.map(
          (r, i) =>
            `${i + 1}. [${r.priority.toUpperCase()}] ${r.title}\n   ${r.description}`
        ),
        "",
        "─".repeat(50),
        "INTERVIEW QUESTIONS",
        "─".repeat(50),
        "",
        ...result.interviewQuestions.map(
          (q, i) =>
            `${i + 1}. [${q.type} / ${q.difficulty}]\n   ${q.question}`
        ),
        "",
        "=".repeat(50),
        "Generated by ResumeAI · Demo analysis only",
        "=".repeat(50),
      ];

      const blob = new Blob([lines.join("\n")], { type: "text/plain" });
      const url = URL.createObjectURL(blob);
      const a = document.createElement("a");
      a.href = url;
      a.download = `resume-analysis-demo-${result.id}.txt`;
      a.click();
      URL.revokeObjectURL(url);
      setExportMsg("Report downloaded as .txt file");
      setTimeout(() => setExportMsg(null), 3000);
    } catch {
      setExportMsg("Export failed — please try again.");
    }
  }, [result]);

  // ── Not found ─────────────────────────────────────────────────────────────
  if (notFound) {
    return (
      <div className="max-w-lg mx-auto px-4 py-24 text-center">
        <div className="w-16 h-16 bg-red-100 rounded-2xl flex items-center justify-center mx-auto mb-5">
          <AlertCircle className="w-8 h-8 text-red-500" />
        </div>
        <h2 className="text-2xl font-bold text-gray-900">Analysis not found</h2>
        <p className="text-gray-500 mt-3 text-sm">
          This analysis may have been deleted or the link is invalid.
          Demo analyses are stored in your browser and cleared if you clear site data.
        </p>
        <div className="flex flex-col sm:flex-row gap-3 justify-center mt-8">
          <Link
            href="/dashboard/resume-analyzer"
            className="inline-flex items-center justify-center gap-2 px-5 py-2.5 bg-blue-600 text-white rounded-xl font-medium hover:bg-blue-700 transition-colors text-sm"
          >
            <PlusCircle className="w-4 h-4" /> New Analysis
          </Link>
          <Link
            href="/dashboard/my-resumes"
            className="inline-flex items-center justify-center gap-2 px-5 py-2.5 bg-white border border-gray-200 text-gray-700 rounded-xl font-medium hover:bg-gray-50 transition-colors text-sm"
          >
            <History className="w-4 h-4" /> View History
          </Link>
        </div>
      </div>
    );
  }

  // ── Loading ───────────────────────────────────────────────────────────────
  if (!result) {
    return (
      <div className="flex items-center justify-center min-h-[400px]">
        <div className="flex items-center gap-3 text-gray-400">
          <svg className="animate-spin w-5 h-5 text-blue-500" fill="none" viewBox="0 0 24 24">
            <circle className="opacity-25" cx="12" cy="12" r="10" stroke="currentColor" strokeWidth="4" />
            <path className="opacity-75" fill="currentColor" d="M4 12a8 8 0 018-8V0C5.373 0 0 5.373 0 12h4z" />
          </svg>
          Loading analysis…
        </div>
      </div>
    );
  }

  // ── Result ────────────────────────────────────────────────────────────────
  return (
    <div className="max-w-4xl mx-auto px-4 sm:px-6 lg:px-8 py-10 space-y-8">
      {/* Back */}
      <Link
        href="/dashboard/my-resumes"
        className="inline-flex items-center gap-2 text-sm text-gray-500 hover:text-gray-800 transition-colors"
      >
        <ArrowLeft className="w-4 h-4" />
        Back to history
      </Link>

      {/* Header card */}
      <div className="bg-white rounded-2xl border border-gray-200 shadow-sm p-6">
        <div className="flex flex-wrap items-start justify-between gap-4">
          {/* Meta */}
          <div className="space-y-1">
            <h1 className="text-2xl font-bold text-gray-900">{result.jobTitle}</h1>
            <div className="flex flex-wrap items-center gap-3 text-sm text-gray-500">
              <span className="flex items-center gap-1.5">
                <Briefcase className="w-4 h-4" />
                {result.targetRole}
              </span>
              <span className="flex items-center gap-1.5">
                <FileText className="w-4 h-4" />
                {result.fileName}
              </span>
              <span className="flex items-center gap-1.5">
                <Calendar className="w-4 h-4" />
                {formatDate(result.createdAt)}
              </span>
            </div>
            {/* Demo badge */}
            <span className="inline-flex items-center gap-1.5 px-2.5 py-1 bg-amber-50 border border-amber-200 text-amber-800 rounded-full text-xs font-medium mt-1">
              <span className="w-1.5 h-1.5 bg-amber-500 rounded-full" />
              Demo Analysis
            </span>
          </div>

          {/* Actions */}
          <div className="flex flex-wrap gap-2">
            <Button
              variant="outline"
              size="sm"
              onClick={handleSave}
              disabled={saved}
            >
              {saved ? "✓ Saved" : "Save Analysis"}
            </Button>
            <Button variant="outline" size="sm" onClick={handleExport}>
              <Download className="w-4 h-4" />
              Export
            </Button>
            <Button
              variant="danger"
              size="sm"
              loading={deleting}
              onClick={handleDelete}
            >
              <Trash2 className="w-4 h-4" />
              Delete
            </Button>
          </div>
        </div>

        {/* Export feedback */}
        {exportMsg && (
          <p className="mt-3 text-xs text-green-700 bg-green-50 border border-green-200 rounded-lg px-3 py-1.5">
            {exportMsg}
          </p>
        )}
      </div>

      {/* Results layout */}
      <AnalysisResultsLayout result={result} />

      {/* Bottom actions */}
      <div className="grid grid-cols-1 sm:grid-cols-3 gap-3 pt-4 border-t border-gray-200">
        <Link
          href="/dashboard/resume-analyzer"
          className="flex items-center justify-center gap-2 px-4 py-3 bg-blue-600 text-white rounded-xl font-medium hover:bg-blue-700 transition-colors text-sm"
        >
          <PlusCircle className="w-4 h-4" />
          Analyze Another Resume
        </Link>
        <Link
          href="/dashboard/my-resumes"
          className="flex items-center justify-center gap-2 px-4 py-3 bg-white border border-gray-200 text-gray-700 rounded-xl font-medium hover:bg-gray-50 transition-colors text-sm"
        >
          <History className="w-4 h-4" />
          View Resume History
        </Link>
        <Link
          href="/analyze"
          className="flex items-center justify-center gap-2 px-4 py-3 bg-purple-600 text-white rounded-xl font-medium hover:bg-purple-700 transition-colors text-sm"
        >
          <FileText className="w-4 h-4" />
          AI Analysis (Live)
        </Link>
      </div>
    </div>
  );
}
