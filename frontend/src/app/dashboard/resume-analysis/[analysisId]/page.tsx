"use client";

import { useEffect, useState, useCallback } from "react";
import { useParams, useRouter } from "next/navigation";
import Link from "next/link";
import { loadAnalysisById, deleteAnalysis } from "@/services/analysisStorage";
import { toAnalysisView, type AnalysisView } from "@/services/mockAnalysisService";
import {
  deleteAiAnalysis,
  getAiAnalysis,
  isDemoAnalysisId,
  regenerateAiAnalysis,
  toAnalysisViewFromAi,
} from "@/services/resumeAnalysisService";
import { toApiClientError } from "@/services/api";
import AnalysisResultsLayout from "@/components/results/AnalysisResultsLayout";
import { formatDate } from "@/lib/utils";
import { ArrowLeft, Download, Trash2, PlusCircle, History, FileText, Calendar, Briefcase, AlertCircle, RefreshCw, Bot, Building2, LogIn } from "lucide-react";
import Button from "@/components/common/Button";

type LoadState = "loading" | "ready" | "not-found" | "error" | "unauthorized";

export default function ResumeAnalysisPage() {
  const params = useParams();
  const router = useRouter();
  const analysisId = params?.analysisId as string;

  const [result, setResult] = useState<AnalysisView | null>(null);
  const [loadState, setLoadState] = useState<LoadState>("loading");
  const [loadError, setLoadError] = useState<string | null>(null);
  const [deleting, setDeleting] = useState(false);
  const [regenerating, setRegenerating] = useState(false);
  const [saved, setSaved] = useState(false);
  const [notice, setNotice] = useState<{ type: "ok" | "error"; text: string } | null>(null);

  const load = useCallback(async () => {
    if (!analysisId) return;
    setLoadState("loading");
    if (isDemoAnalysisId(analysisId)) {
      const data = loadAnalysisById(analysisId);
      if (!data) setLoadState("not-found");
      else {
        setResult(toAnalysisView(data));
        setLoadState("ready");
      }
      return;
    }
    try {
      const record = await getAiAnalysis(analysisId);
      setResult(toAnalysisViewFromAi(record));
      setLoadState("ready");
    } catch (err) {
      const apiErr = toApiClientError(err);
      if (apiErr.status === 404) setLoadState("not-found");
      else if (apiErr.isAuthError) setLoadState("unauthorized");
      else {
        setLoadError(apiErr.message);
        setLoadState("error");
      }
    }
  }, [analysisId]);

  useEffect(() => {
    load();
  }, [load]);

  const flash = (type: "ok" | "error", text: string) => {
    setNotice({ type, text });
    setTimeout(() => setNotice(null), 3000);
  };

  // ── Save (demo analyses are already persisted locally) ────────────────────
  const handleSave = useCallback(() => {
    setSaved(true);
    setTimeout(() => setSaved(false), 2500);
  }, []);

  // ── Delete ────────────────────────────────────────────────────────────────
  const handleDelete = useCallback(async () => {
    if (!result) return;
    if (!confirm("Delete this analysis? This cannot be undone.")) return;
    setDeleting(true);
    try {
      if (result.analysisMode === "ai") await deleteAiAnalysis(result.id);
      else deleteAnalysis(result.id);
      router.push("/dashboard/my-resumes");
    } catch (err) {
      setDeleting(false);
      flash("error", toApiClientError(err).message);
    }
  }, [result, router]);

  // ── Regenerate (AI only) ──────────────────────────────────────────────────
  const handleRegenerate = useCallback(async () => {
    if (!result || result.analysisMode !== "ai") return;
    if (!result.canRegenerate) {
      flash("error", "The resume text was not stored for this analysis, so it cannot be regenerated. Run a new analysis instead.");
      return;
    }
    if (!confirm("Run this analysis again? A new history record will be created and the current result kept.")) return;
    setRegenerating(true);
    try {
      const record = await regenerateAiAnalysis(result.id);
      flash("ok", "New analysis created - opening it.");
      router.push(`/dashboard/resume-analysis/${record.id}`);
    } catch (err) {
      flash("error", toApiClientError(err).message);
    } finally {
      setRegenerating(false);
    }
  }, [result, router]);

  // ── Export ────────────────────────────────────────────────────────────────
  const handleExport = useCallback(() => {
    if (!result) return;
    try {
      const isAi = result.analysisMode === "ai";
      const lines: string[] = [
        isAi ? "RESUME ANALYSIS REPORT — AI ANALYSIS" : "RESUME ANALYSIS REPORT — DEMO DATA",
        "=".repeat(50),
        "",
        isAi
          ? `Generated by ${result.provider ?? "AI provider"}${result.model ? ` (${result.model})` : ""}. The match score is an application-defined estimate, not a hiring probability.`
          : "⚠  This report contains illustrative demo results only.\n   It is NOT based on AI processing of your actual resume.",
        "",
        `Job Title:    ${result.jobTitle}`,
        `Target Role:  ${result.targetRole}`,
        ...(result.companyName ? [`Company:      ${result.companyName}`] : []),
        `Resume File:  ${result.fileName}`,
        `Date:         ${formatDate(result.createdAt)}`,
        `Match Score:  ${result.scoreAvailable === false ? "unavailable (insufficient evidence)" : `${result.matchScore}% (estimate)`}`,
        ...(result.summary ? ["", `Summary: ${result.summary}`] : []),
        "",
        "─".repeat(50), "SKILLS", "─".repeat(50), "",
        "Matched Skills:",
        ...result.skills.filter((s) => s.matchType === "matched").map((s) => `  ✓ ${s.name}${s.evidence ? ` — evidence: ${s.evidence}` : ""}`),
        "",
        "Partial Match:",
        ...result.skills.filter((s) => s.matchType === "partial").map((s) => `  ~ ${s.name}${s.gap ? ` — gap: ${s.gap}` : ""}`),
        "",
        isAi ? "Missing or Unverified Skills:" : "Missing Skills:",
        ...result.skills.filter((s) => s.matchType === "missing").map((s) => `  ✗ ${s.name}${s.reason ? ` — ${s.reason}` : ""}`),
        "",
        "─".repeat(50), "ATS CHECKS", "─".repeat(50), "",
        ...result.atsChecks.map((c) => `[${c.status.toUpperCase()}]${c.verifiability ? ` (${c.verifiability})` : ""} ${c.label}: ${c.detail}`),
        "",
        "─".repeat(50), "STRENGTHS", "─".repeat(50), "",
        ...result.strengths.map((s, i) => `${i + 1}. ${s}`),
        "",
        "─".repeat(50), "RECOMMENDATIONS", "─".repeat(50), "",
        ...result.recommendations.map((r, i) => `${i + 1}. [${r.priority.toUpperCase()}] ${r.title}\n   ${r.description}`),
        "",
        "─".repeat(50), "INTERVIEW QUESTIONS", "─".repeat(50), "",
        ...result.interviewQuestions.map((q, i) => `${i + 1}. [${q.type} / ${q.difficulty}]\n   ${q.question}${q.reason ? `\n   Why: ${q.reason}` : ""}`),
        ...(result.limitations?.length ? ["", "─".repeat(50), "LIMITATIONS", "─".repeat(50), "", ...result.limitations.map((l) => `- ${l}`)] : []),
        "",
        "=".repeat(50),
        isAi ? "Generated by ResumeAI · AI analysis" : "Generated by ResumeAI · Demo analysis only",
        "=".repeat(50),
      ];
      const blob = new Blob([lines.join("\n")], { type: "text/plain" });
      const url = URL.createObjectURL(blob);
      const a = document.createElement("a");
      a.href = url;
      a.download = `resume-analysis-${result.analysisMode}-${result.id}.txt`;
      a.click();
      URL.revokeObjectURL(url);
      flash("ok", "Report downloaded as .txt file");
    } catch {
      flash("error", "Export failed — please try again.");
    }
  }, [result]);

  // ── States ────────────────────────────────────────────────────────────────
  if (loadState === "not-found" || loadState === "error" || loadState === "unauthorized") {
    return (
      <div className="max-w-lg mx-auto px-4 py-24 text-center">
        <div className="w-16 h-16 bg-red-100 rounded-2xl flex items-center justify-center mx-auto mb-5">
          <AlertCircle className="w-8 h-8 text-red-500" />
        </div>
        <h2 className="text-2xl font-bold text-gray-900">
          {loadState === "not-found" ? "Analysis not found" : loadState === "unauthorized" ? "Sign in to view this analysis" : "Could not load analysis"}
        </h2>
        <p className="text-gray-500 mt-3 text-sm">
          {loadState === "not-found" && "This analysis may have been deleted, belong to another account, or the link is invalid. Demo analyses live in this browser and are cleared with site data."}
          {loadState === "unauthorized" && "AI analyses are private to the account that created them."}
          {loadState === "error" && loadError}
        </p>
        <div className="flex flex-col sm:flex-row gap-3 justify-center mt-8">
          {loadState === "unauthorized" ? (
            <Link href={`/auth/login?next=/dashboard/resume-analysis/${analysisId}`} className="inline-flex items-center justify-center gap-2 px-5 py-2.5 bg-blue-600 text-white rounded-xl font-medium hover:bg-blue-700 transition-colors text-sm">
              <LogIn className="w-4 h-4" /> Sign in
            </Link>
          ) : loadState === "error" ? (
            <Button onClick={load}><RefreshCw className="w-4 h-4" /> Retry</Button>
          ) : (
            <Link href="/dashboard/resume-analyzer" className="inline-flex items-center justify-center gap-2 px-5 py-2.5 bg-blue-600 text-white rounded-xl font-medium hover:bg-blue-700 transition-colors text-sm">
              <PlusCircle className="w-4 h-4" /> New Analysis
            </Link>
          )}
          <Link href="/dashboard/my-resumes" className="inline-flex items-center justify-center gap-2 px-5 py-2.5 bg-white border border-gray-200 text-gray-700 rounded-xl font-medium hover:bg-gray-50 transition-colors text-sm">
            <History className="w-4 h-4" /> View History
          </Link>
        </div>
      </div>
    );
  }

  if (loadState === "loading" || !result) {
    return (
      <div className="flex items-center justify-center min-h-[400px]">
        <div className="flex items-center gap-3 text-gray-400">
          <svg className="animate-spin w-5 h-5 text-blue-500" fill="none" viewBox="0 0 24 24">
            <circle className="opacity-25" cx="12" cy="12" r="10" stroke="currentColor" strokeWidth="4" />
            <path className="opacity-75" fill="currentColor" d="M4 12a8 8 0 018-8V0C5.373 0 0 5.373 0 12h4z" />
          </svg>
          Loading analysis…
        </div>
      </div>
    );
  }

  const isAi = result.analysisMode === "ai";

  return (
    <div className="max-w-4xl mx-auto px-4 sm:px-6 lg:px-8 py-10 space-y-8">
      <Link href="/dashboard/my-resumes" className="inline-flex items-center gap-2 text-sm text-gray-500 hover:text-gray-800 transition-colors">
        <ArrowLeft className="w-4 h-4" /> Back to history
      </Link>

      {/* Header card */}
      <div className="bg-white rounded-2xl border border-gray-200 shadow-sm p-6">
        <div className="flex flex-wrap items-start justify-between gap-4">
          <div className="space-y-1">
            <h1 className="text-2xl font-bold text-gray-900">{result.jobTitle}</h1>
            <div className="flex flex-wrap items-center gap-3 text-sm text-gray-500">
              <span className="flex items-center gap-1.5"><Briefcase className="w-4 h-4" />{result.targetRole}</span>
              {result.companyName && <span className="flex items-center gap-1.5"><Building2 className="w-4 h-4" />{result.companyName}</span>}
              <span className="flex items-center gap-1.5"><FileText className="w-4 h-4" />{result.fileName}</span>
              <span className="flex items-center gap-1.5"><Calendar className="w-4 h-4" />{formatDate(result.createdAt)}</span>
            </div>
            {isAi ? (
              <span className="inline-flex items-center gap-1.5 px-2.5 py-1 bg-indigo-50 border border-indigo-200 text-indigo-800 rounded-full text-xs font-medium mt-1">
                <Bot className="w-3 h-3" /> AI Analysis{result.provider ? ` · ${result.provider}` : ""}
              </span>
            ) : (
              <span className="inline-flex items-center gap-1.5 px-2.5 py-1 bg-amber-50 border border-amber-200 text-amber-800 rounded-full text-xs font-medium mt-1">
                <span className="w-1.5 h-1.5 bg-amber-500 rounded-full" /> Demo Analysis
              </span>
            )}
          </div>

          <div className="flex flex-wrap gap-2">
            {isAi ? (
              <Button variant="outline" size="sm" onClick={handleRegenerate} loading={regenerating} title={result.canRegenerate ? "Run the AI analysis again" : "Resume text was not stored, so this cannot be regenerated"}>
                <RefreshCw className="w-4 h-4" /> Regenerate
              </Button>
            ) : (
              <Button variant="outline" size="sm" onClick={handleSave} disabled={saved}>{saved ? "✓ Saved" : "Save Analysis"}</Button>
            )}
            <Button variant="outline" size="sm" onClick={handleExport}><Download className="w-4 h-4" /> Export</Button>
            <Button variant="danger" size="sm" loading={deleting} onClick={handleDelete}><Trash2 className="w-4 h-4" /> Delete</Button>
          </div>
        </div>
        {notice && (
          <p role="status" className={`mt-3 text-xs rounded-lg px-3 py-1.5 border ${notice.type === "ok" ? "text-green-700 bg-green-50 border-green-200" : "text-red-700 bg-red-50 border-red-200"}`}>{notice.text}</p>
        )}
        {regenerating && <p className="mt-3 text-xs text-indigo-700 animate-pulse">Re-running the AI analysis — this usually takes 15–60 seconds…</p>}
      </div>

      <AnalysisResultsLayout result={result} />

      <div className="grid grid-cols-1 sm:grid-cols-3 gap-3 pt-4 border-t border-gray-200">
        <Link href="/dashboard/resume-analyzer" className="flex items-center justify-center gap-2 px-4 py-3 bg-blue-600 text-white rounded-xl font-medium hover:bg-blue-700 transition-colors text-sm">
          <PlusCircle className="w-4 h-4" /> Analyze Another Resume
        </Link>
        <Link href="/dashboard/my-resumes" className="flex items-center justify-center gap-2 px-4 py-3 bg-white border border-gray-200 text-gray-700 rounded-xl font-medium hover:bg-gray-50 transition-colors text-sm">
          <History className="w-4 h-4" /> View Resume History
        </Link>
        <Link href="/dashboard/job-analyzer" className="flex items-center justify-center gap-2 px-4 py-3 bg-white border border-gray-200 text-gray-700 rounded-xl font-medium hover:bg-gray-50 transition-colors text-sm">
          <Briefcase className="w-4 h-4" /> Job Analyzer
        </Link>
      </div>
    </div>
  );
}
